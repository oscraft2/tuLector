/**
 * Equivalencia de un ensayo a puntaje PAES y SIMCE.
 *
 * SIEMPRE se calcula sobre el PORCENTAJE DE LOGRO (correctas / total, o puntos
 * ponderados / puntaje total), nunca sobre un numero fijo de preguntas: un
 * ensayo de 36 preguntas y uno de 65 tienen que poder compararse.
 *
 * ---------------------------------------------------------------------------
 * PAES: tablas OFICIALES del DEMRE, convertidas a porcentaje.
 * ---------------------------------------------------------------------------
 * PAES_TABLES viene de las "Tablas de Transformacion de Puntajes" que publica
 * el DEMRE (demre.cl/paes/factores-seleccion), importadas para los procesos
 * 2025 y 2026, regular e invierno, de las cinco pruebas.
 *
 * La tabla oficial mapea RESPUESTAS CORRECTAS -> puntaje para la PAES real, que
 * tiene su propio largo (60 preguntas M1, 49 M2, 75 Ciencias...). Aca cada fila
 * se convirtio a PORCENTAJE dividiendo por ese largo, que es lo unico que se
 * puede aplicar a un ensayo de 36 o de 40 preguntas. Es una ADAPTACION de la
 * tabla oficial, no la tabla literal: un 50% de logro en un ensayo de 36
 * preguntas recibe el puntaje que el DEMRE le da a un 50% de logro en esa
 * prueba, no el de "18 respuestas correctas".
 *
 * ---------------------------------------------------------------------------
 * SIMCE: sigue siendo APROXIMADO.
 * ---------------------------------------------------------------------------
 * La Agencia de Calidad no publica una tabla equivalente de correctas ->
 * puntaje, asi que SIMCE usa la proporcion sobre el rango 100-400 y viaja con
 * `aproximado: true` para que la interfaz lo rotule. Si aparece una tabla
 * oficial, se carga en SIMCE_TABLES y la marca desaparece sola.
 *
 * Modulo puro (sin "server-only", sin alias) y SOLO de servidor por tamaño:
 * son ~1.200 filas de datos, no tiene por que viajar al navegador.
 */

