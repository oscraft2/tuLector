/** Tablas oficiales de SIMCE. Vacio: la Agencia de Calidad no publica una
 *  conversion de correctas a puntaje comparable a la del DEMRE. */
export const SIMCE_TABLES: ConversionTable[] = [];

/** Tabla por defecto cuando el ensayo no dice a que prueba se parece. */
export const DEFAULT_PAES_TABLE_ID = "m1_regular_2026";

/** Rango de la escala SIMCE (Agencia de Calidad). */
const SIMCE_MIN = 100, SIMCE_MAX = 400;

export type Equivalence = {
  score: number;
  /** true = proporcional, no la conversion oficial. La interfaz lo rotula. */
  aproximado: boolean;
  /** Que tabla se aplico, para poder decirlo en la interfaz. */
  tabla?: string;
};

/**
 * Puntaje que la tabla asigna a un porcentaje de logro. Interpola linealmente
 * entre tramos y satura en los extremos -- mismo criterio que `gradeFromTable`
 * (src/lib/grade_table.ts) para la tabla puntaje->nota del colegio.
 */
export function scoreFromTable(table: ConversionTable, pct: number): number | null {
  const rows = table.rows;
  if (rows.length === 0) return null;

  const x = clamp01(pct) * 100;
  if (x <= rows[0].pct) return Math.round(rows[0].score);
  const last = rows[rows.length - 1];
  if (x >= last.pct) return Math.round(last.score);

  for (let i = 0; i < rows.length - 1; i++) {
    const lo = rows[i];
    const hi = rows[i + 1];
    if (x >= lo.pct && x <= hi.pct) {
      const span = hi.pct - lo.pct;
      if (span <= 0) return Math.round(hi.score);
      const t = (x - lo.pct) / span;
      return Math.round(lo.score + t * (hi.score - lo.score));
    }
  }
  return Math.round(last.score);
}

/** Variante PAES del ensayo (evaluation_variant) -> prueba del DEMRE. */
const VARIANT_A_PRUEBA: Record<string, string> = {
  paes_m1: "m1",
  paes_m2: "m2",
  paes_lectora: "competencia-lectora",
  paes_ciencias: "ciencias",
  paes_historia: "hycsoc",
};

/** Asignatura del ensayo -> prueba del DEMRE, cuando no hay variante PAES.
 *  Heuristica sobre el texto de `quizzes.subject`. */
function pruebaPorAsignatura(subject: string | null | undefined): string | null {
  const s = (subject ?? "").toLowerCase();
  if (!s) return null;
  if (s.includes("matem")) return "m1";
  if (s.includes("lengua") || s.includes("literatura") || s.includes("lectora")) return "competencia-lectora";
  if (s.includes("historia") || s.includes("sociales")) return "hycsoc";
  if (s.includes("biolog") || s.includes("fisica") || s.includes("física") || s.includes("quimica") || s.includes("química") || s.includes("ciencias")) return "ciencias";
  return null;
}

/**
 * Tabla que corresponde a un ensayo: su variante PAES si la tiene, si no la
 * asignatura, y si tampoco, la tabla por defecto. Se prefiere el proceso
 * REGULAR mas reciente disponible para esa prueba.
 */
export function paesTableForQuiz(quiz: {
  evaluation_variant?: string | null;
  subject?: string | null;
}): ConversionTable {
  const prueba =
    VARIANT_A_PRUEBA[String(quiz.evaluation_variant ?? "")] ??
    pruebaPorAsignatura(quiz.subject) ??
    null;

  if (prueba) {
    const regulares = PAES_TABLES.filter((t) => t.id.startsWith(`${prueba}_regular_`));
    if (regulares.length > 0) {
      // El id termina en el año; el mas reciente gana.
      return [...regulares].sort((a, b) => b.id.localeCompare(a.id))[0];
    }
  }
  return PAES_TABLES.find((t) => t.id === DEFAULT_PAES_TABLE_ID) ?? PAES_TABLES[0];
}

/** Puntaje PAES equivalente a un porcentaje de logro. */
export function paesEquivalence(pct: number, table?: ConversionTable): Equivalence {
  const t = table ?? PAES_TABLES.find((x) => x.id === DEFAULT_PAES_TABLE_ID) ?? PAES_TABLES[0];
  const fromTable = t ? scoreFromTable(t, pct) : null;
  if (fromTable !== null) return { score: fromTable, aproximado: false, tabla: t.label };
  // Sin tablas cargadas: proporcional sobre el rango PAES.
  return { score: Math.round(100 + clamp01(pct) * 900), aproximado: true };
}

/** Puntaje SIMCE equivalente a un porcentaje de logro. */
export function simceEquivalence(pct: number, table?: ConversionTable): Equivalence {
  const t = table ?? SIMCE_TABLES[0];
  const fromTable = t ? scoreFromTable(t, pct) : null;
  if (fromTable !== null) return { score: fromTable, aproximado: false, tabla: t.label };
  return { score: Math.round(SIMCE_MIN + clamp01(pct) * (SIMCE_MAX - SIMCE_MIN)), aproximado: true };
}

/** Porcentaje de logro de una hoja. Usa el puntaje PONDERADO cuando el ensayo
 *  lo tiene (points/points_total) y el conteo de correctas cuando no. Devuelve
 *  null si no hay denominador: ahi no se puede afirmar nada. */
export function achievementPct(paper: {
  score?: number | null; total?: number | null;
  points?: number | null; points_total?: number | null;
}): number | null {
  const total = paper.points_total ?? paper.total ?? 0;
  const score = paper.points ?? paper.score ?? 0;
  if (!Number.isFinite(total) || total <= 0) return null;
  return clamp01(score / total);
}

function clamp01(value: number): number {
  if (!Number.isFinite(value)) return 0;
  return Math.max(0, Math.min(1, value));
}
